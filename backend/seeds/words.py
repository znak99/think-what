def seed():
    db = SessionLocal()
    try:
        existing = db.query(Word).count()
        if existing > 0:
            print(f"이미 {existing}개의 단어가 존재합니다. 스킵합니다.")
            return

        words = [Word(word=w, consonants=c) for w, c in WORDS]
        db.add_all(words)
        db.commit()
        print(f"{len(words)}개의 단어를 추가했습니다.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
